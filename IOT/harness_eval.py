_ONE_LAYER = re.compile(r"(?<![A-Za-z0-9])h(\d+)_")


def nested(text):
    """한 층 이름(h101_temp) → 보드가 만드는 세대 컨테이너 구조(h101/temp). 경로·문장 글자 모두에 쓴다.
    측정 기본값은 캐시 재현을 위해 한 층 이름 트리다 — --nested 로 보드와 같은 트리로 잰다."""
    return _ONE_LAYER.sub(r"h\1/", text)


def use_nested(items):
    """FIXTURE 와 정답(제어 규칙 경로, 장치 이름을 그대로 쓴 문장)을 세대 컨테이너 구조로 바꾼다. 제자리에서 바꾼다 —
    FIXTURE 를 참조하는 곳(검증·범위·정답 대조)이 모두 같은 트리를 보게."""
    FIXTURE[:] = [dict(d, path=nested(d["path"])) for d in FIXTURE]
    for it in items:
        it["sentence"] = nested(it["sentence"])
        c = it["expect"].get("control")
        if c:
            c["when_path"], c["then_path"] = nested(c["when_path"]), nested(c["then_path"])


